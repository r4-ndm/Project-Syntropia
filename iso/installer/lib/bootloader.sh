#!/bin/bash
# Limine bootloader installation for the Syntropia installer.
# ----------------------------------------------------------
# The installed system boots Limine, not systemd-boot/GRUB (decision recorded
# in NEXT_SESSION.md). Limine has no "install to ESP" command: on UEFI the
# BOOT*.EFI executable is copied to the ESP, on BIOS `limine bios-install`
# writes the MBR code plus stage 2 into a BIOS boot partition, and both read
# the same limine.conf.
#
# Layout contract with syntropia-install-runner: the ESP is mounted at
# /boot, so everything Limine needs lives at the volume root —
#   /limine.conf          (candidate #5 of Limine's search order: root)
#   /limine-bios.sys      (BIOS stage 2 payload)
#   /EFI/BOOT/BOOTX64.EFI (firmware fallback path)
#   /EFI/limine/BOOTX64.EFI (the NVRAM-registered path)
# The kernel/initramfs are already at /boot/vmlinuz-* and /boot/initramfs-*.
#
# Function bodies only: sourcing this file must not touch the disk. Tests
# source it and drive each function against a temp directory (see
# phase1/tests/test_installer_bootloader.py).
[[ -n "${SYNTROPIA_BOOTLOADER_SH:-}" ]] && return 0
SYNTROPIA_BOOTLOADER_SH=1

# Entry names are spelled exactly like the identity sync expects them
# (iso/hook-scripts/hook-branding-users.sh): it renames CachyOS's
# `/+CachyOS` entry to `/+CachyOS Syntropia` and pins TARGET_OS_NAME to the
# same string, which is also os-release PRETTY_NAME. Generating the final
# name here means limine-snapper-sync's match is already correct before the
# branding hook runs, and the hook's rename stays a no-op for new installs.
LIMINE_ENTRY_NAME="${LIMINE_ENTRY_NAME:-/+CachyOS Syntropia}"
LIMINE_LTS_ENTRY_NAME="${LIMINE_LTS_ENTRY_NAME:-/+CachyOS Syntropia (LTS Kernel)}"
LIMINE_KERNEL="${LIMINE_KERNEL:-vmlinuz-linux-cachyos}"
LIMINE_INITRAMFS="${LIMINE_INITRAMFS:-initramfs-linux-cachyos.img}"
LIMINE_LTS_KERNEL="${LIMINE_LTS_KERNEL:-vmlinuz-linux-cachyos-lts}"
LIMINE_LTS_INITRAMFS="${LIMINE_LTS_INITRAMFS:-initramfs-linux-cachyos-lts.img}"

# Overridable so tests can exercise both firmware paths on any host.
LIMINE_EFIVARS_DIR="${LIMINE_EFIVARS_DIR:-/sys/firmware/efi/efivars}"

# limine_conf_write <boot-dir> <kernel-cmdline> [lts 0|1] [splash-src]
#
# Writes <boot-dir>/limine.conf. `path:` / `module_path:` are relative to
# `boot():` — the volume Limine itself was booted from, i.e. the ESP. The
# interface skin duplicates what the branding hook would add, so a user who
# never runs the hook still gets Syntropia colours, and the hook's
# `grep -q interface_branding` guard skips its own insertion.
#
# splash-src is the Syntropia wallpaper; when it exists it is copied onto the
# ESP and used as the boot menu background (the Calamares path gets the same
# image through limineSplashLogo). Missing file = colour-only menu, never an
# error: the bootloader must not depend on a branding asset.
limine_conf_write() {
    local boot_dir="$1" cmdline="$2" lts="${3:-0}"
    local splash="${4:-/usr/share/syntropia/branding/wallpaper.png}"
    local wallpaper_lines=""
    mkdir -p "$boot_dir"
    if [[ -f "$splash" ]]; then
        install -Dm644 "$splash" "$boot_dir/syntropia-splash.png"
        wallpaper_lines=$'wallpaper: boot():/syntropia-splash.png\nwallpaper_style: stretched\n'
    fi
    cat > "$boot_dir/limine.conf" <<EOF
# Syntropia OS — bootloader configuration.
# Generated by syntropia-install-runner; limine-snapper-sync appends snapshot
# sub-entries under the OS entry, do not rename it by hand.

timeout: 3
default_entry: 1
interface_branding: Syntropia Bootloader
interface_branding_color: bd93f9
term_background: 0f1017
${wallpaper_lines}
$LIMINE_ENTRY_NAME
    protocol: linux
    path: boot():/$LIMINE_KERNEL
    cmdline: $cmdline
    module_path: boot():/$LIMINE_INITRAMFS
EOF

    if [[ "$lts" == "1" ]]; then
        cat >> "$boot_dir/limine.conf" <<EOF

$LIMINE_LTS_ENTRY_NAME
    protocol: linux
    path: boot():/$LIMINE_LTS_KERNEL
    cmdline: $cmdline
    module_path: boot():/$LIMINE_LTS_INITRAMFS
EOF
    fi
}

# limine_install_efi <limine-share-dir> <boot-dir> <disk> <esp-partnum>
#
# Copies the UEFI executable onto the ESP twice — the firmware fallback path
# (survives an NVRAM wipe, and is what a firmware with no boot entries picks)
# and the path NVRAM points at — then registers "Syntropia OS" when the
# running system is UEFI. Registration is best-effort: a firmware that ignores
# efibootmgr still boots /EFI/BOOT/BOOTX64.EFI.
limine_install_efi() {
    local src="$1" boot_dir="$2" disk="$3" partnum="$4"
    local efi="BOOTX64.EFI" bootnum

    if [[ ! -f "$src/$efi" ]]; then
        echo "limine: $src/$efi missing — cannot install the UEFI loader" >&2
        return 1
    fi
    install -Dm644 "$src/$efi" "$boot_dir/EFI/BOOT/BOOTX64.EFI"
    install -Dm644 "$src/$efi" "$boot_dir/EFI/limine/BOOTX64.EFI"

    if [[ ! -d "$LIMINE_EFIVARS_DIR" ]] || ! command -v efibootmgr >/dev/null 2>&1; then
        return 0
    fi

    # Reinstalls otherwise pile up identical NVRAM entries.
    for bootnum in $(efibootmgr 2>/dev/null \
            | sed -n 's/^Boot\([0-9A-Fa-f]\{4\}\)[* ]*Syntropia.*/\1/p'); do
        efibootmgr --delete-bootnum --bootnum "$bootnum" >/dev/null 2>&1 || true
    done

    efibootmgr --create --disk "$disk" --part "$partnum" \
        --label "Syntropia OS" --loader '\EFI\limine\BOOTX64.EFI' >/dev/null \
        || echo "limine: could not register the UEFI boot entry (firmware fallback still boots)" >&2
    return 0
}

# limine_install_bios <limine-share-dir> <boot-dir> <limine-bin> <disk> <bios-partnum>
#
# Limine's BIOS stage 2 lives in a GPT "BIOS boot" partition (type ef02) and
# is loaded at boot from <boot-dir>/limine-bios.sys on the ESP; `limine
# bios-install` writes stage 1 into the MBR and stage 2 into that partition.
limine_install_bios() {
    local src="$1" boot_dir="$2" bin="$3" disk="$4" partnum="$5"

    if [[ ! -f "$src/limine-bios.sys" ]]; then
        echo "limine: $src/limine-bios.sys missing — cannot install the BIOS loader" >&2
        return 1
    fi
    if [[ ! -x "$bin" ]]; then
        echo "limine: $bin not executable — cannot run bios-install" >&2
        return 1
    fi

    install -Dm644 "$src/limine-bios.sys" "$boot_dir/limine-bios.sys"
    "$bin" bios-install "$disk" "$partnum"
}

# limine_tools_dir <target-root>
#
# Prints the directory holding the limine payloads (BOOTX64.EFI,
# limine-bios.sys): the target first (the live rootfs is rsynced to it), then
# the live image as a fallback for an image whose package set changed.
# Returns 1 when neither has them.
limine_tools_dir() {
    local target="$1" candidate
    for candidate in "$target/usr/share/limine" /usr/share/limine; do
        if [[ -f "$candidate/BOOTX64.EFI" && -f "$candidate/limine-bios.sys" ]]; then
            printf '%s' "$candidate"
            return 0
        fi
    done
    return 1
}

# limine_bin <target-root> — the limine host binary for `bios-install`.
limine_bin() {
    local target="$1"
    if [[ -x "$target/usr/bin/limine" ]]; then
        printf '%s' "$target/usr/bin/limine"
    else
        printf '%s' /usr/bin/limine
    fi
}
